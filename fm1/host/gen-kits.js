// Slimehedron for the FM-1: the site's own drum kits as SLOOP synthesized kits.
//   node fm1/host/gen-kits.js      -> fm1/firmware/slime_kits.py (kit lines in SLOOP's gen_drumkits.py format)
// The site builds every drum from oscillators and noise (index.html dHit, KITTONE: kick start / end Hz, dive, decay,
// click; snare noise band and decay, body tone, noise / tone mix; hat pitch, decay and metal amount; crash and tom
// scale). SLOOP's drum synth (firmware/src/drum_synth.c) has the same building blocks per lane: a tone with a pitch
// drop, a click, filtered noise, metal / cymbal noise, a second partial. This writes each site kit in SLOOP's musical
// units (Hz, ms, semitones), voice by voice from dHit's own numbers; SLOOP's level_drumkits.py then levels the lanes.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', '..');
const src = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const m = src.match(/const KITTONE=\{[\s\S]*?\n\};/);
if (!m) throw new Error('KITTONE not found in index.html');
const KITTONE = new Function(m[0] + '\nreturn KITTONE;')();
const ORDER = ['pop', 'rock', 'disco', 'bossa', 'jazz', 'samba', 'conga', 'march', 'chip', 'beep', 'industrial'];
const NAME = { pop: 'SH POP', rock: 'SH ROCK', disco: 'SH DISCO', bossa: 'SH BOSSA', jazz: 'SH JAZZ', samba: 'SH SAMBA',
  conga: 'SH CONGA', march: 'SH MARCH', chip: 'SH CHIP', beep: 'SH BEEP', industrial: 'SH INDUS' };
const r = (x, d = 0) => +x.toFixed(d);
const semis = (a, b) => Math.max(0, Math.round(12 * Math.log2(a / b)));
const L = ['# GENERATED by fm1/host/gen-kits.js from index.html (KITTONE, dHit). Do not edit: change the site and rerun.',
  '# Inserted into SLOOP\'s tools/gen_drumkits.py KITS by fm1/firmware/patch_kits.py. GPL-3.0-or-later.'];
for (const k of ORDER) {
  const T = KITTONE[k];
  // KICK: a sine diving from kf to ke (808: over 60% of the decay, else min(120 ms, 35%)), decay kd, a noise click kc
  const dive = T.st === '808' ? T.kd * 0.6 : Math.min(0.12, T.kd * 0.35);
  const kick = `S("sine", ${r(T.ke, 1)}, ${semis(T.kf, T.ke)}, ${r(dive * 1000)}, 0, ${r(T.kd * 1000)}, ${Math.min(127, r(124 * T.kv))}, click=${Math.min(127, r(71 * T.kc))})`;
  // SNARE: band-passed (brush: high-passed) noise at sf for sd, a triangle body at sb falling to 0.6x over 0.7 sd and
  // ending at 0.8 sd, mixed by sn (noise 0.4 sn, body 0.26 (1 - 0.6 sn)); the stick style adds a woody click
  const n = 0.4 * T.sn, t = 0.26 * (1 - 0.6 * T.sn), mx = Math.max(n, t);
  const sfilt = T.st === 'brush' ? `("hp", ${T.sf}, .1)` : `("bp", ${T.sf}, .25)`;
  const snare = `S("tri", ${r(T.sb * 0.6, 1)}, 9, ${r(T.sd * 700)}, 0, ${r(T.sd * 800)}, ${r(118 * t / mx)}, ` +
    `click=${T.st === 'stick' ? 40 : 0}, src="white", nlev=${r(118 * n / mx)}, ndec=${r(T.sd * 1000)}, filt=${sfilt})`;
  // HATS: six detuned squares at hf/2 (metal) and airy noise high-passed at hf, hm the metal share; the open hat rings
  // 0.34 + 2 hd
  const hsrc = T.hm >= 0.5 ? 'metal' : 'cym';
  const chh = `S(None, ${r(T.hf * 0.5)}, src="${hsrc}", nlev=114, ndec=${r(T.hd * 1000)}, filt=("hp", ${r(T.hf)}, .25), hpf=${r(T.hf * 0.85)}, click=10)`;
  const ohh = `S(None, ${r(T.hf * 0.5)}, src="${hsrc}", nlev=110, nhold=20, ndec=${r((0.34 + T.hd * 2) * 1000)}, filt=("hp", ${r(T.hf * 0.92)}, .25), hpf=${r(T.hf * 0.8)})`;
  // TOMS: a sine from 1.45x down onto 98 / 156 Hz (x tm) in 70 ms, a 1.59x drumhead mode, a 25 ms noise thump at 1.1 kHz
  const tm = T.tm || 1;
  const tom = (f, d) => `S("sine", ${r(f * tm, 1)}, 6, 70, 0, ${d}, 118, 1.59, 40, 0, "white", 46, 0, 25, ("bp", 1100, .2))`;
  // CONGA (the site's 'c'): a triangle from 1.18 to 0.68 of 210 Hz in 100 ms, 170 ms; a noise slap at 3x
  const conga = `S("tri", ${r(210 * 0.68, 1)}, 10, 100, 0, 170, 110, src="white", nlev=40, ndec=30, filt=("bp", 630, .3))`;
  // RIM: a 28 ms 2.1 kHz noise tick over a 420 -> 210 Hz knock
  const rim = `S("tri", 210, 12, 20, 0, 30, 70, src="white", nlev=116, ndec=28, filt=("bp", 2100, .5))`;
  // CLAVE: a 2.5 kHz sine gone in 60 ms, a short 3.2 kHz noise click
  const clave = `S("sine", 2500, 0, 5, 0, 60, 110, src="white", nlev=60, ndec=8, filt=("bp", 3200, .4))`;
  // CRASH: metal at 390 Hz (x cy) under bright noise for 1.9 s; RIDE: a small sine bell, its octave
  const cy = T.cy || 1;
  const crash = `S(None, ${r(390 * cy)}, src="metal", nlev=110, nhold=10, ndec=1900, filt=("hp", ${r(3800 * cy)}, .2))`;
  const ride = `S("bell", 1046.5, 0, 5, 0, 600, 100, 2.0, 40)`;
  L.push(`    ("${NAME[k]}", "SLIMEHEDRON", 0, kit(K909,   # the site's ${k} (KITTONE.${k}: ${T.st})`,
    `        KICK=${kick},`, `        SNARE=${snare},`, `        CHH=${chh},`, `        OHH=${ohh},`,
    `        TOMLO=${tom(98, 500)},`, `        TOMHI=${tom(156, 380)},`, `        CONGA=${conga},`, `        RIM=${rim},`,
    `        CLAVE=${clave},`, `        CRASH=${crash},`, `        RIDE=${ride})),`);
}
// what each kit's kick must measure, for check-host.sh: the site's end pitch (Hz) and decay to -60 dB (ms)
fs.writeFileSync(path.join(root, 'fm1', 'firmware', 'slime_kits_expect.json'), JSON.stringify(Object.fromEntries(ORDER.map(k => [NAME[k], { ke: KITTONE[k].ke, kd: Math.round(KITTONE[k].kd * 1000) }])), null, 1) + '\n');
const out = path.join(root, 'fm1', 'firmware', 'slime_kits.py');
fs.writeFileSync(out, L.join('\n') + '\n');
console.log('wrote', out, ORDER.length, 'kits');
