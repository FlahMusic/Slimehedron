// Slimehedron for the FM-1: lifts the web app's drum patterns (KITS), the genre feels (FEELS, FEEL_DEFAULT) and the
// fill / crash tables out of index.html and writes them as C tables (fm1/core/band_tables.h). The objects are
// EVALUATED, not retyped, so the device plays exactly the site's grooves.   node fm1/host/gen-band.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', '..');
const src = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
function grab(re, what) { const m = src.match(re); if (!m) throw new Error('not found in index.html: ' + what); return m[0]; }
const code = [
  grab(/function rep\(base,bars\)\{[^\n]*\}/, 'rep'),
  grab(/function bars\(\.\.\.b\)\{[^\n]*\}/, 'bars'),
  grab(/const KITS=\{[\s\S]*?\n\};/, 'KITS'),
  grab(/const KITVOICE=\{[^\n]*\n[^\n]*\};/, 'KITVOICE'),
  grab(/const FEELS=\{[\s\S]*?\n\};/, 'FEELS'),
  grab(/const FEEL_DEFAULT=\{[\s\S]*?\};/, 'FEEL_DEFAULT'),
  grab(/const TOM_FILL=\{[^}]*\};/, 'TOM_FILL'),
  grab(/const CRASH_ON_KEY=\{[^}]*\};/, 'CRASH_ON_KEY'),
  grab(/const KITFEEL=\{[\s\S]*?\n\};/, 'KITFEEL'),
  grab(/const KITFEEL_DEFAULT=\{[^\n]*\};/, 'KITFEEL_DEFAULT'),
  grab(/const SIMPLE=\{[^}]*\}/, 'SIMPLE (drumSchedule)'),
  'module.exports={KITS,KITVOICE,FEELS,FEEL_DEFAULT,TOM_FILL,CRASH_ON_KEY,KITFEEL,KITFEEL_DEFAULT,SIMPLE};'].join('\n');
const M = {}; new Function('module', code)(M);
const { KITS, KITVOICE, FEELS, FEEL_DEFAULT, TOM_FILL, CRASH_ON_KEY, KITFEEL, KITFEEL_DEFAULT, SIMPLE } = M.exports;

const ORDER = ['pop', 'rock', 'disco', 'bossa', 'jazz', 'samba', 'conga', 'march', 'chip', 'beep', 'industrial'];
// the web's voice letters -> General MIDI notes on the FM-1's synthesized kits (SLOOP drums.c LANE_NOTE has these lanes):
// K kick 36, s snare 38, h closed hat 42, o open hat 46, r rim 37, cl the bossa clave on the rim 37 (as records play it:
// the web's own comment), c conga 63, C tom / low conga 43, y ride 51; fills: ht hi tom 48, lt low tom 43; x crash 49
// 2026-11-20: the site's own DRUMN (index.html), every piece its own note: the FM-1 plays the site's drum recipes itself now
// (fm1/firmware/slime_drums.c), so the clave is not the rim and the high conga is not a tom (they shared 37 and 43 before)
const GM = { K: 36, s: 38, h: 42, o: 46, r: 37, cl: 75, c: 62, C: 63, y: 51, ht: 50, lt: 45, x: 49 };
const VOICES = ['K', 's', 'h', 'o', 'r', 'cl', 'c', 'C', 'y'];
for (const k of ORDER) for (const v in KITS[k]) if (!VOICES.includes(v)) throw new Error('unmapped voice ' + v + ' in ' + k);
const mask = steps => { let lo = 0, hi = 0; for (const s of steps) { if (s < 32) lo |= (1 << s) >>> 0; else hi |= (1 << (s - 32)) >>> 0; } return '0x' + ((BigInt(hi >>> 0) << 32n) | BigInt(lo >>> 0)).toString(16).padStart(16, '0') + 'ull'; };
const L = [];
L.push('/* GENERATED by fm1/host/gen-band.js from index.html (KITS, KITVOICE, FEELS, FEEL_DEFAULT, TOM_FILL, CRASH_ON_KEY).');
L.push(' * Do not edit: change the site, then run the generator. GPL-3.0-or-later. The rhythm sources and their credits are in');
L.push(' * the site (index.html, THIRD-PARTY.md): pop / rock / disco / bossa / jazz from casio-music-data by Nicholas Opuni. */');
L.push('#ifndef SH_BAND_TABLES_H\n#define SH_BAND_TABLES_H\n#include <stdint.h>');
L.push(`#define SH_NKITS ${ORDER.length}\n#define SH_NDV ${VOICES.length}`);
L.push(`static const char *const SH_KIT_NAME[SH_NKITS] = {${ORDER.map(k => '"' + k + '"').join(', ')}};`);
L.push(`/* the drum voices: ${VOICES.join(' ')} as General MIDI notes */`);
L.push(`static const uint8_t SH_DV_NOTE[SH_NDV] = {${VOICES.map(v => GM[v]).join(', ')}};`);
L.push(`enum { SH_GM_HT = ${GM.ht}, SH_GM_LT = ${GM.lt}, SH_GM_CRASH = ${GM.x} };`);
L.push('/* each kit: 64 sixteenth steps (4 bars) per voice, bit s = step s */');
L.push('static const uint64_t SH_KIT_STEPS[SH_NKITS][SH_NDV] = {');
for (const k of ORDER) L.push(`  {${VOICES.map(v => mask(KITS[k][v] || [])).join(', ')}},   /* ${k} */`);
L.push('};');
const vi = v => VOICES.indexOf(v);
L.push('/* each kit\'s low / mid / high voice (index into SH_DV_NOTE): fills are built from these */');
L.push(`static const uint8_t SH_KIT_LMH[SH_NKITS][3] = {${ORDER.map(k => `{${vi(KITVOICE[k].lo)}, ${vi(KITVOICE[k].mid)}, ${vi(KITVOICE[k].hi)}}`).join(', ')}};`);
L.push(`static const uint8_t SH_TOM_FILL[SH_NKITS] = {${ORDER.map(k => TOM_FILL[k] ? 1 : 0).join(', ')}};`);
L.push(`static const uint8_t SH_CRASH_ON_KEY[SH_NKITS] = {${ORDER.map(k => CRASH_ON_KEY[k] ? 1 : 0).join(', ')}};`);
L.push('typedef struct {');
L.push('  double seed_odds, push, dodge; uint8_t ring, arp_fill, density[2];');
L.push('  uint8_t nseeds, seeds[6][8], seed_n[6];      /* the genre\'s textbook chord rhythms */');
L.push('  uint8_t w[16];                               /* chance of a chord hit on each 16th */');
L.push('  int8_t progs[4][4];                          /* its own chord changes, scale degrees */');
L.push('  double artic[3];                             /* block, arp, broken */');
L.push('  double seventh, ninth, sus; uint8_t v7;');
L.push('  uint8_t bw[16], bdensity[2]; double boct, bapproach;   /* the bass */');
L.push('  uint8_t fill_every, fill_len;');
L.push('} sh_feel;');
const f2 = x => String(+x);   // doubles, as the web's: a float 0.6 flips weighted picks at a boundary
function feelC(f, name) {
  const seeds = f.seeds.slice(0, 6);
  const sd = seeds.map(s => `{${s.concat(Array(8 - s.length).fill(0)).join(',')}}`);
  while (sd.length < 6) sd.push('{0}');
  const sn = seeds.map(s => s.length); while (sn.length < 6) sn.push(0);
  const a = f.artic || { block: 1 };
  return `  {${f2(f.seedOdds)}, ${f2(f.push)}, ${f2(f.dodge == null ? 0.5 : f.dodge)}, ${f.ring ? 1 : 0}, ${f.arpFill ? 1 : 0}, {${f.density.join(',')}},\n` +
    `   ${seeds.length}, {${sd.join(',')}}, {${sn.join(',')}},\n   {${f.w.join(',')}},\n` +
    `   {${f.progs.slice(0, 4).map(p => `{${p.join(',')}}`).join(',')}},\n` +
    `   {${f2(a.block || 0)}, ${f2(a.arp || 0)}, ${f2(a.broken || 0)}}, ${f2(f.colour.seventh || 0)}, ${f2(f.colour.ninth || 0)}, ${f2(f.colour.sus || 0)}, ${f.colour.v7 ? 1 : 0},\n` +
    `   {${f.bass.w.join(',')}}, {${f.bass.density.join(',')}}, ${f2(f.bass.oct)}, ${f2(f.bass.approach)},\n   ${f.fill.every}, ${f.fill.len}},   /* ${name} */`;
}
// the drummer's feel per style (KITFEEL, drumSchedule's SIMPLE): humanize amounts, swing, accents per drum per step
L.push('/* the drummer\'s feel (KITFEEL): humanize dyn / time / ghost, swung 8ths (jazz) and 16ths (bossa), ghosts on the "&"');
L.push(' * only (jazz), ghost hats, SIMPLE kits (fewer ghosts, no pickup); accents per drum per step, in percent */');
L.push('typedef struct { double dyn, time, ghost, sw8, sw16; uint8_t ghost_and, ghost_hat, simple; uint8_t acc[SH_NDV][16]; } sh_kitfeel;');
L.push('static const sh_kitfeel SH_KITFEEL[SH_NKITS] = {');
for (const k of ORDER) {
  const kf = KITFEEL[k] || KITFEEL_DEFAULT;
  const acc = VOICES.map(v => {
    const a = (kf.acc || {})[v], row = [];
    for (let st = 0; st < 16; st++) row.push(Math.round(100 * (a == null ? 1 : typeof a === 'number' ? a : (a[st] != null ? a[st] : 1))));
    return '{' + row.join(',') + '}';
  });
  L.push(`  {${+kf.dyn}, ${+kf.time}, ${+kf.ghost}, ${+(kf.sw8 || 0)}, ${+(kf.sw16 || 0)}, ${kf.ghostAt === 'and' ? 1 : 0}, ` +
    `${kf.ghostHat === false ? 0 : 1}, ${SIMPLE[k] ? 1 : 0},\n   {${acc.join(',')}}},   /* ${k}${KITFEEL[k] ? '' : ' (the default feel)'} */`);
}
L.push('};');
L.push('static const sh_feel SH_FEEL[SH_NKITS] = {');
for (const k of ORDER) L.push(feelC(FEELS[k] || FEEL_DEFAULT, k + (FEELS[k] ? '' : ' (the house feel)')));
L.push('};\n#endif');
const out = path.join(root, 'fm1', 'core', 'band_tables.h');
fs.writeFileSync(out, L.join('\n') + '\n');
console.log('wrote', out, ORDER.length, 'kits');
