// ============================================================================================
//  SOLID REFERENCE: the web's own solid maths, lifted out of index.html (from `const SOLID_R` to
//  `function solidSlice`) and run in node, written to _dev/solid-ref.json. The plugin core
//  (vst/slimehedron-core/src/tank/solid.rs) and the FM-1 core (fm1/core/solid.c) test against it, so
//  a change to the web's solids shows up as a red test on both. Rerun after any change there:
//    node _dev/solid-ref.js
// ============================================================================================
const fs=require('fs'),path=require('path');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const a=html.indexOf('const SOLID_R='),b=html.indexOf('function solidSlice');
if(a<0||b<0)throw new Error('solid code not found in index.html');
const R=300,BOXD=R*1.2;
let TD=21;const totalDegrees=()=>TD;
const code=html.slice(a,b)+'\nreturn {solidPlanes,solidFaces,solidVerts,solidFaceDegrees,isOrbName,ORB_MINF,ORB_MAXF};';
const M=new Function('R','BOXD','totalDegrees','wallDegrees',code)(R,BOXD,totalDegrees,()=>{throw new Error('wallDegrees: only orbs here');});
const names=['tetra','cube','octa','dodeca','icosa','prism3','prism6','prism12','cube.cut','icosa.cut','cube.flip','cube.puff',
  'octa.cut','dodeca.flip','tetra.cut.flip','orb12','orb21','orb31','orb62','orb93','orb124'];
const r6=x=>Math.round(x*1e6)/1e6;
const out={note:'generated by _dev/solid-ref.js from index.html; R=300, BOXD=360, td=21 for orb notes',td:TD,shapes:{}};
for(const n of names){const P=M.solidPlanes(n),F=M.solidFaces(P),V=M.solidVerts(F);
  out.shapes[n]={planes:P.map(p=>[...p.n.map(r6),r6(p.d)]),faces:F.length,verts:V.length,
    edges:V.reduce((s,v)=>s+v.nb.size,0)/2,deg:M.isOrbName(n)?M.solidFaceDegrees(P,n):null};}
fs.writeFileSync(path.join(__dirname,'solid-ref.json'),JSON.stringify(out));
console.log('wrote _dev/solid-ref.json:',names.length,'shapes');
