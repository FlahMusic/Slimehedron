// ============================================================================================
//  CURVED SPACE REFERENCE: the web's own hyperbolic-tank maths, lifted out of index.html (from `const HYP=` to
//  `function buildEdges(`, and `function hypSub` to `function step(){`) and run in node, written to
//  _dev/space-ref.json. The FM-1 core (fm1/core/space.c) tests against it, so a change to the web's curved space
//  shows up as a red test there. Rerun after any change to those parts of index.html:
//    node _dev/space-ref.js
//  Everything is in DISK units (the Poincare disk's radius = 1), so the numbers do not depend on the screen size.
//  The calls into sound, splashes and the wobble are stubbed (a hit is recorded instead; jitter is off), and a few
//  balls are flown for a fixed number of ticks through regular 3- to 8-gons in curved space.
// ============================================================================================
const fs=require('fs'),path=require('path');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const a=html.indexOf('const HYP='),b=html.indexOf('function buildEdges('),c=html.indexOf('function hypSub('),d=html.indexOf('function step(){',c);
if(a<0||b<0||c<0||d<0||!(a<b)||!(c<d))throw new Error('curved-space code not found in index.html');
const R=300,CX=360,CY=360,BR=9;
const W={edges:null,hits:[]};
const code=html.slice(a,b)+'\n'+html.slice(c,d)+'\nreturn {HYP,hypCorner,curveEdges,hypSub,mdot,hP,set:(e)=>{edges=e;}};';
// what the lifted code reaches for outside itself, stubbed
const stubs={R,CX,CY,BR,isSolidName:()=>false,shapeVerts:()=>{throw new Error('shapeVerts: not here');},LAB:null,VIEW:{d3:false},ctx:null,BOXD:R*1.2,
  jitter:()=>{},splash:()=>{},gooAt:()=>0,stageHalfW:()=>R,performance:{now:()=>0},
  trigger:(cents)=>{W.hits.push(cents);}};
const names=Object.keys(stubs);
const M=new Function(...names,'let edges=null,_splashZ=0,_hitPan=0;\n'+code)(...names.map(k=>stubs[k]));
const r9=x=>Math.round(x*1e9)/1e9;
const out={note:'generated by _dev/space-ref.js from index.html; disk units (radius 1); R=300, RD='+M.HYP.RD+', BR=9 (='+r9(BR/M.HYP.RD)+' disk), UV='+M.HYP.UV,
  RD:M.HYP.RD,UV:M.HYP.UV,brDisk:r9(BR/M.HYP.RD),shapes:{}};
let seed=20261111;const rnd=()=>((seed=(seed*1103515245+12345)%2147483648)/2147483648);
for(let N=3;N<=8;N++){
  // the web's own regular N-gon (spin 0), its corners pushed into the disk the way buildEdges does for 'curved'
  const hc=M.hypCorner(N),verts=[];
  for(let i=0;i<N;i++){const t=-Math.PI/2+i*2*Math.PI/N;verts.push([CX+hc.u*M.HYP.RD*Math.cos(t),CY+hc.u*M.HYP.RD*Math.sin(t)]);}
  const edges=[];for(let i=0;i<N;i++){const[ax,ay]=verts[i],[bx,by]=verts[(i+1)%N];edges.push({ax,ay,bx,by,cents:i*100,hue:i/N,flash:0,broken:false});}
  M.curveEdges(edges,verts);M.set(edges);
  const D=v=>[r9((v[0]-CX)/M.HYP.RD),r9((v[1]-CY)/M.HYP.RD)];
  const walls=edges.map(e=>({N:e.N.map(r9),arc:e.cr?{cx:r9((e.ccx-CX)/M.HYP.RD),cy:r9((e.ccy-CY)/M.HYP.RD),r:r9(e.cr/M.HYP.RD),a0:r9(e.a0),a1:r9(e.a1),ccw:!!e.ccw}:null}));
  // three balls, each flown 900 ticks at 2 sub-steps a tick (isub 0.5); a hit is the wall's index
  const flights=[];
  for(let k=0;k<3;k++){const ang=rnd()*Math.PI*2,rr=rnd()*0.3,spd=2+rnd()*4;
    // the start is kept to the last bit (no rounding): the flight is chaotic, so a start rounded to 1e-9 parts from
    // the web's within a few bounces. The web ball flies from exactly these numbers.
    const start={x:Math.cos(ang)*rr,y:Math.sin(ang)*rr,vx:Math.cos(ang*1.7)*spd/M.HYP.RD,vy:Math.sin(ang*1.7)*spd/M.HYP.RD},path=[],hits=[];
    const ball={x:CX+start.x*M.HYP.RD,y:CY+start.y*M.HYP.RD,vx:start.vx*M.HYP.RD,vy:start.vy*M.HYP.RD,mute:0};
    for(let t=0;t<900;t++){for(let s=0;s<2;s++){W.hits.length=0;const gone=M.hypSub(ball,0.5,1);
        if(W.hits.length)hits.push([t,s,W.hits[0]/100]);if(gone){path.push(null);break;}}
      if(path[path.length-1]===null)break;
      if(t%30===29)path.push([r9((ball.x-CX)/M.HYP.RD),r9((ball.y-CY)/M.HYP.RD),r9(ball.vx/M.HYP.RD),r9(ball.vy/M.HYP.RD)]);}
    flights.push({start,path,hits});}
  out.shapes[N]={k:hc.k,u:r9(hc.u),corners:verts.map(D),walls,flights};}
fs.writeFileSync(path.join(__dirname,'space-ref.json'),JSON.stringify(out));
console.log('wrote _dev/space-ref.json: curved 3- to 8-gons,',Object.values(out.shapes).reduce((n,s)=>n+s.flights.reduce((m,f)=>m+f.hits.length,0),0),'wall hits in 18 flights');
